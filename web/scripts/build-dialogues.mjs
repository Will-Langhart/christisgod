// Generates src/lib/dialogues.generated.ts from the approved verified library in
// service/library/*.json (produced by the Phase 1 runner). Groups the per-persona
// answers under each objection, in the objection order from objections.ts.
//
// Run:  node scripts/build-dialogues.mjs
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { objections } from "../src/lib/objections.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIB = join(ROOT, "..", "service", "library");
const OUT = join(ROOT, "src", "lib", "dialogues.generated.ts");

// Display order + labels for the interlocutor personas (gentlest first).
const PERSONAS = [
  { id: "seeker", label: "Honest seeker", blurb: "A new believer trying to understand." },
  { id: "skeptic", label: "Skeptic", blurb: "Historical-critical objections." },
  { id: "muslim", label: "Muslim", blurb: "From an Islamic view of Christ." },
  { id: "jw-unitarian", label: "JW / Unitarian", blurb: "Strict-monotheist objections." },
];

async function main() {
  const files = (await readdir(LIB)).filter((f) => f.endsWith(".json"));
  const byQuestion = new Map(); // question -> Map(persona -> {answer, refs})
  for (const f of files) {
    const d = JSON.parse(await readFile(join(LIB, f), "utf8"));
    const refs = [
      ...new Set((d.citations ?? []).filter((c) => c.ok && c.display).map((c) => c.display)),
    ];
    if (!byQuestion.has(d.objection)) byQuestion.set(d.objection, new Map());
    byQuestion.get(d.objection).set(d.persona, { answer: d.answer, refs });
  }

  const sets = objections
    .map((o) => {
      const answers = PERSONAS
        .map((p) => {
          const a = byQuestion.get(o.question)?.get(p.id);
          return a ? { persona: p.id, answer: a.answer, refs: a.refs } : null;
        })
        .filter(Boolean);
      return answers.length
        ? { question: o.question, href: o.href, linkLabel: o.linkLabel, answers }
        : null;
    })
    .filter(Boolean);

  const body =
    `// AUTO-GENERATED by scripts/build-dialogues.mjs. Do not edit by hand.\n` +
    `// Source: the approved verified library in service/library/.\n\n` +
    `export type DialogueAnswer = { persona: string; answer: string; refs: string[] };\n` +
    `export type DialogueSet = {\n` +
    `  question: string;\n  href: string;\n  linkLabel: string;\n  answers: DialogueAnswer[];\n};\n\n` +
    `export const dialoguePersonas = ${JSON.stringify(PERSONAS, null, 2)} as const;\n\n` +
    `export const dialogues: DialogueSet[] = ${JSON.stringify(sets, null, 2)};\n`;

  await writeFile(OUT, body, "utf8");
  const total = sets.reduce((n, s) => n + s.answers.length, 0);
  console.log(`✓ wrote ${sets.length} objections, ${total} dialogues → ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
